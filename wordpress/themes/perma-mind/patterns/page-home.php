<p class="bw-eyebrow">Zertifizierung</p>
<!-- /wp:paragraph --><!-- wp:heading {"className":"bw-heading-section"} -->
<h2 class="wp-block-heading bw-heading-section">Europäische Zertifizierung mit ECQA</h2>
<!-- /wp:heading --></div>
<!-- /wp:group --><!-- wp:paragraph {"className":"bw-text"} -->
<p class="bw-text">Mit einem ECQA-Abschluss erhältst du ein europäisch ausgerichtetes Zertifikat, das deine nachgewiesenen Kompetenzen dokumentiert. Die Zertifizierung erfolgt in einem externen Rahmen mit definierten fachlichen Anforderungen. Für dich entsteht ein Nachweis, dessen Grundlage über die Bewertung durch unsere Academy hinausgeht.</p>
<!-- /wp:paragraph --><!-- wp:paragraph {"className":"bw-text"} -->
<p class="bw-text">Bei der Wahl einer Ausbildung lohnt sich ein Blick auf den Abschluss: Eine reine Teilnahmebestätigung bescheinigt den Besuch eines Lehrgangs. Ein institutseigenes Zertifikat folgt den Anforderungen des jeweiligen Anbieters und kann ebenfalls eine Prüfung voraussetzen. ECQA ergänzt die Ausbildung um die Zertifizierung durch eine unabhängige Stelle anhand festgelegter Kompetenzen und Bewertungskriterien.</p>
<!-- /wp:paragraph --><!-- wp:buttons {"className":"bw-cert__button"} -->
<div class="wp-block-buttons bw-cert__button"><!-- wp:button {"className":"is-style-secondary"} -->
<div class="wp-block-button is-style-secondary"><a class="wp-block-button__link wp-element-button" href="#ausbildungen">Ausbildungen und Abschlüsse vergleichen</a></div>
<!-- /wp:button --></div>
<!-- /wp:buttons --></div>
<!-- /wp:group --><!-- wp:group {"className":"bw-split__aside"} -->
<div class="wp-block-group bw-split__aside"><!-- wp:paragraph {"className":"bw-cert__logo"} -->
<p class="bw-cert__logo"><mark class="bw-placeholder">[ECQA-Logo nach Freigabe]</mark></p>
<!-- /wp:paragraph --><!-- wp:group {"className":"bw-accordion-list"} -->
<div class="wp-block-group bw-accordion-list"><!-- wp:details {"className":"bw-accordion"} -->
<details class="wp-block-details bw-accordion"><summary>Dein Vorteil gegenüber einem rein internen Abschluss</summary><!-- wp:paragraph {"className":"bw-text"} -->
<p class="bw-text">Du kannst deine Qualifikation nachvollziehbar darstellen: Gegenüber Arbeitgeber:innen und Auftraggeber:innen verweist du auf einen externen Kompetenznachweis. Das ist besonders hilfreich, wenn dein Gegenüber den Ausbildungsanbieter noch nicht kennt.</p>
<!-- /wp:paragraph --><!-- wp:paragraph {"className":"bw-text"} -->
<p class="bw-text">Du erkennst, was der Abschluss voraussetzt: Definierte Kompetenzen und Bewertungskriterien machen die Anforderungen transparent. Deine Kenntnisse und Fähigkeiten werden überprüft; die bloße Teilnahme reicht für das ECQA-Zertifikat nicht aus.</p>
<!-- /wp:paragraph --><!-- wp:paragraph {"className":"bw-text"} -->
<p class="bw-text">Du erhältst einen europäisch ausgerichteten Nachweis: ECQA arbeitet über einzelne Bildungsanbieter und Länder hinweg. Das erleichtert es, den Abschluss auch in internationalen beruflichen Zusammenhängen zu erläutern. Eine automatische berufliche Zulassung in anderen Ländern ist damit nicht verbunden.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details --><!-- wp:details {"className":"bw-accordion"} -->
<details class="wp-block-details bw-accordion"><summary>Vom Lernen zum nachgewiesenen Können</summary><!-- wp:paragraph {"className":"bw-text"} -->
<p class="bw-text">Die Vorbereitung auf den Abschluss ist mit der Ausbildung verbunden. Du setzt dich mit wissenschaftlichen Grundlagen auseinander, übst ihre Anwendung und bearbeitest die vorgesehenen Praxisaufgaben. Bei Basic steht dabei dein eigenes Projekt im Mittelpunkt, bei Advanced die vertiefte Anwendung und Trainingsgestaltung, bei Clinical Expert die klinische Praxis einschließlich Supervision.</p>
<!-- /wp:paragraph --><!-- wp:paragraph {"className":"bw-text"} -->
<p class="bw-text">Die Zertifizierungsgebühren sind im Lehrgangspreis nicht enthalten. Ihre Höhe wird noch bekannt gegeben. Die konkreten Abschlussanforderungen erhältst du mit der Ausschreibung.</p>
